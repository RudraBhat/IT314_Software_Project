    probabilities = []

    for start in tqdm(range(0, len(text_list), batch_size), desc="Predicting test set"):
        batch_texts = [str(x) for x in text_list[start:start + batch_size]]
        enc = tokenizer(
            batch_texts,
            truncation=True,
            max_length=MAX_LENGTH,
            padding=True,
            pad_to_multiple_of=8,
            return_tensors="pt",
        )
        enc = {key: value.to(DEVICE) for key, value in enc.items()}

        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=True):
            logits = model(**enc).logits

        probs = torch.softmax(logits.float(), dim=1)
        predictions.extend(torch.argmax(probs, dim=1).cpu().numpy().tolist())
        probabilities.extend(probs.cpu().numpy().tolist())

    return np.asarray(predictions), np.asarray(probabilities)


