warmup_steps = int(total_training_steps * WARMUP_RATIO)

from transformers import get_linear_schedule_with_warmup

scheduler = get_linear_schedule_with_warmup(
    optimizer,
    num_warmup_steps=warmup_steps,
    num_training_steps=total_training_steps,
)

# Automatic mixed precision (FP16) is enabled for the Colab GPU.
try:
    scaler = torch.amp.GradScaler("cuda", enabled=True)
except (AttributeError, TypeError):
    scaler = torch.cuda.amp.GradScaler(enabled=True)

history = []
best_val_f1 = -1.0
epochs_without_improvement = 0
best_epoch = None

for epoch in range(NUM_EPOCHS):
    model.train()
    running_loss = 0.0
    seen_rows = 0
    optimizer.zero_grad(set_to_none=True)

    progress = tqdm(train_loader, desc=f"Epoch {epoch + 1}/{NUM_EPOCHS}")
    for step, batch in enumerate(progress):
        batch = move_batch_to_device(batch)
        batch_size = batch["labels"].size(0)

        # Correctly scale the final, possibly incomplete gradient-accumulation group.
        group_start = (step // GRAD_ACCUM_STEPS) * GRAD_ACCUM_STEPS
        group_size = min(GRAD_ACCUM_STEPS, len(train_loader) - group_start)

        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=True):
            outputs = model(**batch)
            loss = outputs.loss / group_size

        scaler.scale(loss).backward()

        running_loss += outputs.loss.item() * batch_size
        seen_rows += batch_size

        should_update = (
            (step + 1) % GRAD_ACCUM_STEPS == 0
            or (step + 1) == len(train_loader)
        )

        if should_update:
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            scaler.step(optimizer)
            scaler.update()
            scheduler.step()
            optimizer.zero_grad(set_to_none=True)

        progress.set_postfix(loss=f"{outputs.loss.item():.4f}")

    train_loss = running_loss / max(seen_rows, 1)
    val_metrics, val_true, val_pred = evaluate_model(model, val_loader)

    epoch_record = {
        "epoch": epoch + 1,
        "train_loss": train_loss,
        "val_loss": val_metrics["loss"],
        "val_accuracy": val_metrics["accuracy"],
        "val_macro_f1": val_metrics["macro_f1"],
        "val_weighted_f1": val_metrics["weighted_f1"],
        "learning_rate": scheduler.get_last_lr()[0],
    }
    history.append(epoch_record)

    print("\\nEpoch summary:")
    print(json.dumps(epoch_record, indent=2))

    # Persist training history after every epoch so it survives a session interruption.
    pd.DataFrame(history).to_csv(PROJECT_DIR / "training_history.csv", index=False)

    if val_metrics["macro_f1"] > best_val_f1 + 1e-5:
        best_val_f1 = val_metrics["macro_f1"]
        best_epoch = epoch + 1
        epochs_without_improvement = 0

        model.save_pretrained(BEST_MODEL_DIR, safe_serialization=True)
        tokenizer.save_pretrained(BEST_MODEL_DIR)

        with open(BEST_MODEL_DIR / "label_mapping.json", "w", encoding="utf-8") as f:
            json.dump(
                {"label2id": label2id, "id2label": {str(k): v for k, v in id2label.items()}},
                f,
                ensure_ascii=False,
                indent=2,
            )

        with open(PROJECT_DIR / "best_validation_metrics.json", "w", encoding="utf-8") as f:
            json.dump(
                {"best_epoch": best_epoch, **val_metrics},
                f,
                indent=2,
            )

        print(f"Saved new best checkpoint at epoch {best_epoch} (macro-F1={best_val_f1:.4f})")
    else:
        epochs_without_improvement += 1
        print(f"No validation macro-F1 improvement ({epochs_without_improvement}/{EARLY_STOPPING_PATIENCE}).")

    if epochs_without_improvement >= EARLY_STOPPING_PATIENCE:
        print("Early stopping triggered.")
        break

print(f"\\nTraining finished. Best epoch: {best_epoch}; best validation macro-F1: {best_val_f1:.4f}")
