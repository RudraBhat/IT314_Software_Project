"""## 6. Build PyTorch datasets and data loaders"""

class DisasterTextDataset(Dataset):
    def __init__(self, frame, tokenizer, max_length):
        self.texts = frame["text"].astype(str).tolist()
        self.labels = frame["label_id"].astype(int).tolist()
        self.encodings = tokenizer(
            self.texts,
            truncation=True,
            max_length=max_length,
            padding=False,
        )

    def __len__(self):
        return len(self.labels)

    def __getitem__(self, idx):
        item = {
            key: torch.tensor(value[idx], dtype=torch.long)
            for key, value in self.encodings.items()
        }
        item["labels"] = torch.tensor(self.labels[idx], dtype=torch.long)
        return item


def collate_batch(features):
    # Dynamic padding keeps batches efficient; labels are collated separately.
    labels = torch.tensor([int(item["labels"]) for item in features], dtype=torch.long)
    model_inputs = [
        {key: value.tolist() for key, value in item.items() if key != "labels"}
        for item in features
    ]
    batch = tokenizer.pad(
        model_inputs,
        padding=True,
        pad_to_multiple_of=8,
        return_tensors="pt",
    )
    batch["labels"] = labels
    return batch


