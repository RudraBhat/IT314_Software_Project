"""
## 8. Define evaluation helpers

We select the best checkpoint using **validation macro-F1**, not accuracy alone. Macro-F1 gives each of the five classes equal importance.
"""

from sklearn.metrics import f1_score

def move_batch_to_device(batch):
    return {key: value.to(DEVICE, non_blocking=True) for key, value in batch.items()}


@torch.no_grad()
def evaluate_model(model, data_loader):
    model.eval()
    all_labels = []
    all_preds = []
    total_loss = 0.0
    total_rows = 0

    for batch in tqdm(data_loader, desc="Evaluating", leave=False):
        batch = move_batch_to_device(batch)
        labels = batch["labels"]

        with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=True):
            outputs = model(**batch)

        batch_size = labels.size(0)
        total_loss += outputs.loss.item() * batch_size
        total_rows += batch_size

        preds = torch.argmax(outputs.logits, dim=1)
        all_labels.extend(labels.detach().cpu().numpy().tolist())
        all_preds.extend(preds.detach().cpu().numpy().tolist())

    metrics = {
        "loss": total_loss / max(total_rows, 1),
        "accuracy": accuracy_score(all_labels, all_preds),
        "macro_f1": f1_score(all_labels, all_preds, average="macro"),
        "weighted_f1": f1_score(all_labels, all_preds, average="weighted"),
    }
    return metrics, np.asarray(all_labels), np.asarray(all_preds)

"""
## 9. Fine-tune MuRIL

The model is evaluated after every epoch. Whenever validation macro-F1 improves, the model and tokenizer are saved to Google Drive. Training stops early after two consecutive epochs without an improvement.

The original held-out test file is not opened or used here.
"""

BEST_MODEL_DIR = PROJECT_DIR / "muril_disaster_classifier_best"
